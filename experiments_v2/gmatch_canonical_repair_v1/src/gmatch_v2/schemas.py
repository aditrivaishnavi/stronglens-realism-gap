ALLOWLIST_CONTRACT_SHA256 = canonical_json_sha256(
    {
        "schemas": {
            context: sorted(columns) for context, columns in sorted(SCHEMAS.items())
        },
        "forbidden_aliases": sorted(FORBIDDEN_ALIASES),
        "unknown_columns": "reject",
    }
)


def assert_context_schema(
    frame: pd.DataFrame,
    *,
    context: str,
) -> None:
    """Reject every missing, duplicate, or unknown column for this context."""
    if context not in SCHEMAS:
        raise ContractError(f"unregistered dataframe context: {context}")
    observed = list(map(str, frame.columns))
    duplicates = sorted({column for column in observed if observed.count(column) > 1})
    expected = SCHEMAS[context]
    missing = sorted(expected - set(observed))
    unknown = sorted(set(observed) - expected)
    if duplicates or missing or unknown:
        alias_hits = sorted(set(unknown) & FORBIDDEN_ALIASES)
        raise ContractError(
            f"{context} violates strict schema allowlist; "
            f"missing={missing}, unknown={unknown}, duplicates={duplicates}, "
            f"forbidden_aliases={alias_hits}"
        )
